// 收口轮的两段提示词：正常验收，以及「证据核不上」时的补验。
//
// 抽出来的理由：它们是收口流程里最该被反复打磨的文本（措辞直接影响模型判不判得准），
// 放在 800 行的控制流里没人愿意改。这里只做字符串拼装，零副作用，可以单独比对。

import type { Ask, Phase } from '../protocol/schema.ts';

/** 正常收口：把下级交付整理给上级判断 */
export function buildReviewBrief(origin: string, reports: string[], asks: Ask[] = []): string {
  return [
    // 收口轮必须能看到原始要求，否则上级会按自己的理解放宽标准
    ...(origin ? ['## 原始任务（当时给它的要求，验收以这个为准）', origin, ''] : []),
    // 下级点名在问你：这一段的优先级高于验收，别让它沉在长报告里
    ...(asks.length
      ? [
          '## 下级在等你回答（不处理就别判它通过）',
          ...asks.map((a) => `- ${a.from ?? '下级'} 问：${a.question}`),
          '',
          '两条路，必须选一条：',
          '1. **你能定** —— 在 dispatch 里派回提问的那个下级，把答案写进 task 开头，让它带着答案接着干',
          '2. **你定不了** —— 用你自己的 question 升级给人，写清你需要谁拍板、拍什么',
          '直接判通过、不回答，这一轮会被判无效。',
          '',
        ]
      : []),
    '## 下级交回的结果',
    '',
    reports.join('\n\n'),
    '',
    '## 你的判断',
    '**先看上面「实际内容」，逐条对照原始任务的验收标准。** 不要只凭它自己说「做完了」就判合格。',
    '这次交付能不能用。能用就 dispatch 写 []，这一轮结束。',
    '',
    // 多段任务必须能「推进」，否则收口只有「通过」和「打回」两条路，
    // 主控跑到第一段就会顺手写 dispatch [] 收场（#45 四段任务只做完审计段就是这么没的）
    '## 先看一件事：原任务是不是分了几段',
    '原任务里如果写了「第一段/第二段」这种分阶段要求，或者给了一份交付清单，先回答：**到这一轮为止，几段做完了？**',
    '- 各段都做完、清单里点名的路径都在盘上 → dispatch 写 []，这一轮结束',
    '- 只做完其中一段（清单里还有路径没落地）→ 这一轮不是收口，dispatch 派下一段：',
    '  写清这一段的输入、产物路径、验收口径，别把上一段已经过验收的内容再抄一遍。',
    '  **派下一段不算打回**，不要用「哪里不合格」的口气写，也不要因此重开上一段。',
    '',
    '不能用就重新派给同一个下级，dispatch 里的 task **必须写清三件事**，缺一件都算你没尽到责任：',
    '1. **哪里不合格** —— 具体到文件名、字段、行为，不要写「不够好」这种空话',
    '2. **怎么改** —— 可执行的动作，让它照着做就行，不要让它自己猜',
    '3. **改完怎么验** —— 验收口径，写清什么状态算过',
    '',
    '如果上一轮已经打回过，这次要点名「上次要求 X，这次还是 Y」，让它知道错在哪。',
    '最多再派一次，同一件事不要反复推；实在定不了就用 question 说明。',
  ].join('\n');
}

/** 补验：判了通过但证据在产物里搜不到，把「你的结论被驳回」拍回去 */export function buildVerifyBrief(origin: string, miss: string[]): string {
  return [
    ...(origin ? ['## 原始任务（验收以这个为准）', origin, ''] : []),
    '## 你的上一轮结论被驳回',
    '你判了「通过」，但下面这些「证据」在产物里一段都搜不到：',
    ...miss.map((x) => '- 「' + x + '」'),
    '',
    '这通常意味着你没打开文件，或者抄的是自己概括过的话。现在重新判一次：',
    '1. 打开产物文件，逐字读一遍',
    '2. 真的达标：dispatch 写 []，evidence 换成 2 条以上从文件里**原样复制**的片段（标点、缩进都要一样）',
    '3. 不达标：dispatch 打回给下级，写清哪里不合格、怎么改、改完怎么验',
  ].join('\n');
}

/**
 * 阶段推进简报：上一段过了，把下一段交给主控。
 *
 * 为什么要单独一段提示词：只写「继续」的话，主控很可能把上一段又做一遍，
 * 或者干脆判 pass 结束（#45 的四段审计就是这么丢了后三段）。
 * 这里必须同时说清三件事——已完成什么、现在做什么、后面还剩什么。
 */
export function buildPhaseBrief(plan: Phase[], done: string[], next: Phase): string {
  const nth = plan.findIndex((p) => p.id === next.id) + 1;
  const doneNames = plan.filter((p) => done.includes(p.id)).map((p) => p.name);
  const restNames = plan.filter((p) => !done.includes(p.id) && p.id !== next.id).map((p) => p.name);
  return [
    `## 阶段推进：第 ${nth}/${plan.length} 段 —「${next.name}」`,
    '',
    `已完成的段落：${doneNames.length ? doneNames.join(' → ') : '（无）'}`,
    `现在要做的：**${next.name}**`,
    next.doneWhen ? `这一段的验收口径：${next.doneWhen}` : '这一段的验收口径：按原任务里对它的要求判。',
    restNames.length ? `后面还有：${restNames.join(' → ')}` : '这是最后一段，做完就可以收口。',
    '',
    '## 这一轮怎么做',
    '1. 只做这一段，不要重复已完成的段落，也不要提前跳过后面。',
    '2. 把活派给该做的节点，写清这一段的交付物与验收口径。',
    '3. 收口时按这一段的验收口径判；判通过只代表这一段过了，框架会把下一段交给你。',
    '4. 回执里用 phase 字段写明：「' + next.id + '」。',
    '5. 如果这一段定不了、需要人拍板，用 question 或 ask 停下，不要硬做。',
  ].join('\n');
}
